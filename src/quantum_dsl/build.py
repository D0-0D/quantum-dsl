# -*- coding: utf-8 -*-
"""编排 (契约「build 编排 / 分块 / two_pads 锚 / sung 外部锚」): ``build(meta, out_dir, solve=)``。

产物: GDS (+ ``<stem>.gds.png`` 预览) + mesh + Palace config + manifest (输入 sha256); ``extract.blocks``
时另派生 ``block_<name>.geo`` (只含该块 component 的 Physical 组, 其余组整行
删除 —— 几何留作孤儿面, build_mesh 会清) + 各块 mesh/config。

几何源二选一: ``meta.geo`` 手写 ``.geo``, 或 ``meta.layout`` 版图 → ``compile_layout``
编译成 Layout (可调用几何源, 记账 qubits / subsystems 并入 circuit_model / results); 分块时
``Layout.for_block`` 在模型内按 component 过滤, 不派生 ``.geo``。

分块是 quasi-lumped 近似 (SPEC「切块纪律」): 跨块直接互容 = 结构性零。
廉价防线 (docs/physics.md §11): 不同块且从不共现的导体对若几何邻近
(bbox 间距 < airbox.side_um) 则 warn —— 有意直接耦合的导体对必须同块共现。

``solve=True``: 跑 Palace (env ``PALACE_BIN``, ⚠ ``HWLOC_COMPONENTS=-gl``
在 WSL 必须; ``QDSL_PALACE_NP`` 控 rank 数, 默认 1) → parse_capacitance →
circuit_model (meta 的 E_J 系频率 Hz = E_J/h, 此处 ×h 转焦耳) →
``results.yaml`` (hamiltonian + capacitance)。
"""

from __future__ import annotations

import glob
import hashlib
import math
import os
import re
import subprocess
import warnings
from dataclasses import asdict
from itertools import combinations
from pathlib import Path

import yaml

from .circuit_model import H_PLANCK, solve_circuit_model
from .errors import QuantumDslError
from .gds import build_gds, gds_map, jj_gds_layers, render_gds_png
from .geo import parse_physical_name
